import { useState } from 'react'
import { BookOpen, CircleCheck, Download, Lightbulb, ListTree, RefreshCw, Sparkles } from 'lucide-react'
import { AiJobAlerts, GenerateIntro, GeneratingPanel } from './AiPanels'
import SourceChips from './SourceChips'
import { Button, CardToolbar, ConfirmDialog, Skeleton } from './ui'
import { cancelAiJob, dismissAiJob, startAiJob, useAiJob } from '../lib/aiJobs'
import { formatDate } from '../lib/format'
import { downloadTextFile, notesToMarkdown } from '../lib/notesMarkdown'

const INCLUDED = [
  { icon: BookOpen, label: 'Lecture summary' },
  { icon: ListTree, label: 'Topic-wise notes' },
  { icon: Lightbulb, label: 'Concepts and definitions' },
  { icon: CircleCheck, label: 'Key takeaways' },
]

function DocHeading({ id, icon: Icon, children }) {
  return (
    <h2 id={id} className="flex scroll-mt-28 items-center gap-2 text-lg font-semibold tracking-tight text-ink-900">
      <Icon className="size-[18px] text-accent-500" aria-hidden="true" />
      {children}
    </h2>
  )
}

function NotesSkeleton() {
  return (
    <div className="mx-auto max-w-3xl space-y-8">
      <div className="space-y-2.5">
        <Skeleton className="h-5 w-32" />
        <Skeleton className="h-3.5 w-full" />
        <Skeleton className="h-3.5 w-11/12" />
        <Skeleton className="h-3.5 w-3/4" />
      </div>
      {[0, 1].map((i) => (
        <div key={i} className="space-y-2.5">
          <Skeleton className="h-4 w-48" />
          <Skeleton className="h-3.5 w-full" />
          <Skeleton className="h-3.5 w-5/6" />
        </div>
      ))}
    </div>
  )
}

/** "On this page" links for long notes; shown beside the document on wide screens. */
function NotesOutline({ items }) {
  return (
    <nav aria-label="On this page" className="sticky top-20 hidden w-44 shrink-0 self-start xl:block">
      <p className="text-xs font-medium text-ink-500">On this page</p>
      <ul className="mt-2 space-y-0.5 border-l border-ink-200">
        {items.map(({ id, label }) => (
          <li key={id}>
            <button
              type="button"
              onClick={() => document.getElementById(id)?.scrollIntoView?.({ behavior: 'smooth', block: 'start' })}
              className="-ml-px w-full border-l border-transparent py-1 pl-3 text-left text-sm text-ink-500 transition-colors duration-150 hover:border-ink-400 hover:text-ink-900"
            >
              {label}
            </button>
          </li>
        ))}
      </ul>
    </nav>
  )
}

function Notes({ lecture, notes, onJump, onRegenerate }) {
  const handleDownload = () => downloadTextFile(`${lecture.title} - notes.md`, notesToMarkdown(lecture, notes), 'text/markdown')
  const outline = [
    { id: 'notes-summary', label: 'Summary' },
    notes.takeaways.length > 0 && { id: 'notes-takeaways', label: 'Key takeaways' },
    notes.sections.length > 0 && { id: 'notes-topics', label: 'Topic notes' },
    notes.concepts.length > 0 && { id: 'notes-concepts', label: 'Concepts' },
  ].filter(Boolean)

  return (
    <div>
      <CardToolbar
        actions={
          <>
            <Button variant="secondary" onClick={onRegenerate} className="flex-1 sm:flex-none">
              <RefreshCw className="size-4" aria-hidden="true" />
              Regenerate
            </Button>
            <Button variant="secondary" onClick={handleDownload} className="flex-1 sm:flex-none">
              <Download className="size-4" aria-hidden="true" />
              Download .md
            </Button>
          </>
        }
      >
        <p className="text-xs text-ink-500">
          Generated by {notes.model} on {formatDate(notes.generated_at)}. Click a timestamp to see the source.
        </p>
      </CardToolbar>

      <div className="flex justify-center gap-10 px-4 py-6 sm:px-8 sm:py-8">
        <article className="w-full max-w-3xl min-w-0 space-y-10">
          <section>
            <DocHeading id="notes-summary" icon={BookOpen}>
              Summary
            </DocHeading>
            <p className="mt-3 text-[15px] leading-7 text-ink-700">{notes.summary}</p>
          </section>

          {notes.takeaways.length > 0 && (
            <section>
              <DocHeading id="notes-takeaways" icon={CircleCheck}>
                Key takeaways
              </DocHeading>
              <ol className="mt-3 space-y-2.5 rounded-xl border border-ink-200 bg-ink-50 p-4">
                {notes.takeaways.map((takeaway, i) => (
                  <li key={i} className="flex gap-3">
                    <span className="flex size-5 shrink-0 items-center justify-center rounded-full bg-accent-100 text-[11px] font-semibold text-accent-700 tabular-nums sm:mt-0.5">
                      {i + 1}
                    </span>
                    <p className="min-w-0 text-sm leading-6 text-ink-800">
                      {takeaway.text} <SourceChips sources={takeaway.sources} onJump={onJump} />
                    </p>
                  </li>
                ))}
              </ol>
            </section>
          )}

          {notes.sections.length > 0 && (
            <section>
              <DocHeading id="notes-topics" icon={ListTree}>
                Topic notes
              </DocHeading>
              <div className="mt-2 divide-y divide-ink-100">
                {notes.sections.map((section, i) => (
                  <article key={i} className="py-5 first:pt-2 last:pb-0">
                    <div className="flex flex-col gap-1.5 sm:flex-row sm:items-start sm:justify-between sm:gap-4">
                      <h3 className="text-[15px] font-semibold text-ink-900">
                        <span className="mr-1.5 font-medium text-ink-500 tabular-nums">{i + 1}.</span>
                        {section.title}
                      </h3>
                      <SourceChips sources={section.sources} onJump={onJump} />
                    </div>
                    {section.summary && <p className="mt-1 text-sm leading-6 text-ink-500">{section.summary}</p>}
                    {section.points.length > 0 && (
                      <ul className="mt-2.5 space-y-1.5 pl-5 text-[15px] leading-7 text-ink-700 marker:text-ink-300 [&>li]:list-disc">
                        {section.points.map((point, j) => (
                          <li key={j}>{point}</li>
                        ))}
                      </ul>
                    )}
                  </article>
                ))}
              </div>
            </section>
          )}

          {notes.concepts.length > 0 && (
            <section>
              <DocHeading id="notes-concepts" icon={Lightbulb}>
                Concepts and definitions
              </DocHeading>
              <dl className="mt-3 grid grid-cols-1 gap-3 md:grid-cols-2">
                {notes.concepts.map((concept, i) => (
                  <div key={i} className="rounded-xl border border-ink-200 p-4">
                    <dt className="text-sm font-semibold text-ink-900">{concept.term}</dt>
                    <dd className="mt-1 text-sm leading-6 text-ink-600">{concept.definition}</dd>
                    {concept.sources.length > 0 && (
                      <dd className="mt-2">
                        <SourceChips sources={concept.sources} onJump={onJump} />
                      </dd>
                    )}
                  </div>
                ))}
              </dl>
            </section>
          )}
        </article>
        <NotesOutline items={outline} />
      </div>
    </div>
  )
}

/** Notes tab: generate, show, regenerate, and export Gemini study notes. `onJump({start, end})` opens the transcript. */
export default function NotesView({ lecture, onJump }) {
  const job = useAiJob('notes', lecture.id)
  const [confirmRegenerate, setConfirmRegenerate] = useState(false)
  const { notes } = lecture

  if (job?.status === 'loading') {
    return (
      <GeneratingPanel job={job} label="Generating notes…" onCancel={() => cancelAiJob('notes', lecture.id)}>
        <NotesSkeleton />
      </GeneratingPanel>
    )
  }

  const generate = () => startAiJob('notes', lecture)

  return (
    <>
      <AiJobAlerts
        job={job}
        errorTitle="Couldn't generate notes"
        what="Notes"
        onRetry={generate}
        onDismiss={() => dismissAiJob('notes', lecture.id)}
      />
      {notes ? (
        <Notes lecture={lecture} notes={notes} onJump={onJump} onRegenerate={() => setConfirmRegenerate(true)} />
      ) : (
        <GenerateIntro
          icon={Sparkles}
          title="Generate study notes"
          description="Gemini reads this transcript and writes structured notes. Every item links back to the part of the lecture it came from, so you can check it against the source."
          included={INCLUDED}
          buttonLabel="Generate notes"
          onGenerate={generate}
          hasTranscript={lecture.segments.length > 0}
        />
      )}
      {confirmRegenerate && (
        <ConfirmDialog
          title="Regenerate these notes?"
          confirmLabel="Regenerate"
          onCancel={() => setConfirmRegenerate(false)}
          onConfirm={() => {
            setConfirmRegenerate(false)
            generate()
          }}
        >
          <p>The current notes will be replaced with a new version.</p>
        </ConfirmDialog>
      )}
    </>
  )
}
