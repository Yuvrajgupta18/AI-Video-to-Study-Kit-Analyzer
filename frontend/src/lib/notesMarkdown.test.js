import { describe, expect, it } from 'vitest'
import { formatRange, notesToMarkdown } from './notesMarkdown'
import { NOTES, makeLecture } from '../test/fixtures'

describe('notesToMarkdown', () => {
  const markdown = notesToMarkdown(makeLecture(), NOTES)

  it('includes the title, model, and summary', () => {
    expect(markdown).toMatch(/^# ML Basics: Study Notes\n/)
    expect(markdown).toContain('_Generated by gemini-3.6-flash on')
    expect(markdown).toContain('## Summary\n\nAn introduction to supervised learning and gradient descent.')
  })

  it('numbers topic sections and cites source timestamps', () => {
    expect(markdown).toContain('### 1. Supervised learning _(0:03–0:07)_')
    expect(markdown).toContain('### 2. Gradient descent _(0:07–0:13)_')
    expect(markdown).toContain('- Minimizes a loss function.\n- Used to train models.')
  })

  it('lists concepts and takeaways, omitting empty citations', () => {
    expect(markdown).toContain('- **Gradient descent**: Minimizes a loss function. _(0:07–0:13)_')
    expect(markdown).toContain('1. Labeled data drives supervised learning.\n')
  })

  it('skips empty sections', () => {
    const empty = notesToMarkdown(makeLecture(), { ...NOTES, concepts: [], takeaways: [] })
    expect(empty).not.toContain('## Concepts')
    expect(empty).not.toContain('## Key Takeaways')
  })
})

describe('formatRange', () => {
  it('formats hour-long ranges', () => {
    expect(formatRange({ start: 3725, end: 3790.5 })).toBe('1:02:05–1:03:10')
  })
})
