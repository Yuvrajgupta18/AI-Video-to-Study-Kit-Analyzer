import { formatDate, formatTimestamp } from './format'

export function formatRange({ start, end }) {
  return `${formatTimestamp(start)}–${formatTimestamp(end)}`
}

function cite(sources = []) {
  return sources.length ? ` _(${sources.map(formatRange).join(', ')})_` : ''
}

/** Study notes as a Markdown document. Timestamps refer to the original recording. */
export function notesToMarkdown(lecture, notes) {
  const lines = [
    `# ${lecture.title}: Study Notes`,
    '',
    `_Generated by ${notes.model} on ${formatDate(notes.generated_at)}. Timestamps refer to the lecture recording._`,
    '',
    '## Summary',
    '',
    notes.summary,
    '',
  ]

  if (notes.takeaways.length) {
    lines.push('## Key Takeaways', '')
    notes.takeaways.forEach((t, i) => lines.push(`${i + 1}. ${t.text}${cite(t.sources)}`))
    lines.push('')
  }

  if (notes.sections.length) {
    lines.push('## Topic Notes', '')
    notes.sections.forEach((section, i) => {
      lines.push(`### ${i + 1}. ${section.title}${cite(section.sources)}`, '')
      if (section.summary) lines.push(section.summary, '')
      section.points.forEach((point) => lines.push(`- ${point}`))
      lines.push('')
    })
  }

  if (notes.concepts.length) {
    lines.push('## Concepts & Definitions', '')
    notes.concepts.forEach((c) => lines.push(`- **${c.term}**: ${c.definition}${cite(c.sources)}`))
    lines.push('')
  }

  return lines.join('\n')
}

export function downloadTextFile(fileName, text, type = 'text/plain') {
  const blob = new Blob([text], { type: `${type};charset=utf-8` })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = fileName
  link.click()
  URL.revokeObjectURL(url)
}
